        <p style="margin-bottom: 4px;">Schedule quarterly training for teams on the latest in analytics advancements.</p>
        <p>Encourage cross-team training among different teams.</p>
    </li>
    <li style="margin-bottom: 16px;">
        <strong>Data Collection Standardization</strong>
        <p style="margin-bottom: 4px;">Create a company-wide policy for data collection.</p>
        <p>Use templates and tools that support data uniformity.</p>
    </li>
    <li style="margin-bottom: 16px;">
        <strong>Analytics Tool Assessment</strong>
        <p style="margin-bottom: 4px;">List down features needed versus features offered by tools.</p>
